public class Switch {
    public static void main(String[] args) {
     int a = 3;
     switch ( a ) {
        case 1 :
        System.out.println("sunday");
        case 2 :
        System.out.println("monday");
        break ;
        case 3 :
        System.out.println("thrusday");
        default :
        System.out.println("saturday to sunday");


     }   
    }
    
}
